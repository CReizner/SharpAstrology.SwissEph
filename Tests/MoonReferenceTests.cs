using System.Text.Json;
using SharpAstrology.SwissEphemerides;
using SharpAstrology.SwissEphemerides.Application.Bodies;
using SharpAstrology.SwissEphemerides.Domain.Mathematics;
using SharpAstrology.SwissEphemerides.Domain.Frames;
using SharpAstrology.SwissEphemerides.Domain.Time;
using Xunit;

namespace SharpAstrology.SwissEph.Tests;

public class MoonReferenceTests
{
    [Theory]
    [InlineData(2440000.5, PrecessionModel.Iau1976)]
    [InlineData(2460680.5, PrecessionModel.Iau1976)]
    [InlineData(2440000.5, PrecessionModel.Iau2006)]
    [InlineData(2460680.5, PrecessionModel.Iau2006)]
    public void MoshierTrueMoonRetainsEclipticOfDateWithCustomPrecession(double tt, PrecessionModel model)
    {
        // The lunar theory supplies ecliptic-of-date positions. The conversion
        // into J2000 and back must use the same context's precession model.
        using var standard = new EphemerisContextBuilder().Build();
        using var custom = new EphemerisContextBuilder().UseModels(
            AstronomicalModelOverrides.Default with
            {
                PrecessionLongTerm = model,
                PrecessionShortTerm = model,
            }).Build();
        const EphemerisFlags flags = EphemerisFlags.MoshierEph | EphemerisFlags.TruePosition
            | EphemerisFlags.NoNutation | EphemerisFlags.Icrs;
        var jd = new JulianDay(tt);
        var expected = standard.Bodies.Compute(CelestialBody.Moon, jd, flags);
        var actual = custom.Bodies.Compute(CelestialBody.Moon, jd, flags);
        Assert.True((actual.Position - expected.Position).Length < 1e-13);
    }

    // Generated by tools/export_moon_reference.py from the local C sources.
    // All six components are checked; velocity is AU/day, position is AU.
    public static IEnumerable<object[]> ReferenceCases()
    {
        using var document = JsonDocument.Parse(File.ReadAllText(
            Path.Combine(AppContext.BaseDirectory, "TestData", "MoonReference.json")));
        var observer = document.RootElement.GetProperty("observer").EnumerateArray()
            .Select(value => value.GetDouble()).ToArray();
        foreach (var row in document.RootElement.GetProperty("cases").EnumerateArray())
        {
            yield return new object[]
            {
                row.GetProperty("tt").GetDouble(),
                (EphemerisFlags)row.GetProperty("flags").GetInt32(),
                row.GetProperty("vector").EnumerateArray().Select(value => value.GetDouble()).ToArray(),
                new ObserverLocation(observer[0], observer[1], observer[2]),
            };
        }
    }

    [Theory]
    [MemberData(nameof(ReferenceCases))]
    public void MoonPositionAndVelocityMatchC(double tt, EphemerisFlags flags, double[] expected, ObserverLocation observer)
    {
        var builder = new EphemerisContextBuilder();
        if ((flags & EphemerisFlags.SwissEph) != 0)
            builder.UseSwissEphFiles(EphePath.Resolve()).DisableMoshier();
        using var context = builder.Build();
        var result = context.Bodies.Compute(CelestialBody.Moon, new JulianDay(tt), flags, observer);

        Assert.Equal((flags & EphemerisFlags.SwissEph) != 0 ? EphemerisSource.SwissEph : EphemerisSource.Moshier, result.Source);
        double[] actual = [result.Position.X, result.Position.Y, result.Position.Z,
            result.Velocity.X, result.Velocity.Y, result.Velocity.Z];

        // Heliocentric Moshier differences include the existing Earth theory
        // residual. Three-position velocities amplify floating-point differences;
        // topocentric NoAberration also retains a small observer-precession residual.
        var helio = (flags & EphemerisFlags.Heliocentric) != 0;
        var topo = (flags & EphemerisFlags.Topocentric) != 0;
        var sampled = topo || (flags & EphemerisFlags.Speed3) != 0;
        var positionTolerance = helio ? 5e-12 : 1e-13;
        var velocityTolerance = topo ? 2e-11 : helio || sampled ? 5e-12 : 1e-12;
        for (var i = 0; i < 6; i++)
        {
            var tolerance = i < 3 ? positionTolerance : velocityTolerance;
            Assert.True(Math.Abs(actual[i] - expected[i]) <= tolerance,
                $"JD {tt:R}, {flags}, component {i}: expected {expected[i]:R}, actual {actual[i]:R}, tolerance {tolerance:R}");
        }
        if ((flags & (EphemerisFlags.Speed | EphemerisFlags.Speed3)) == 0)
            Assert.Equal(Vec3.Zero, result.Velocity);
    }
}
